// Converts a mysqldump of the Tejasvi database into PostgreSQL (Supabase) SQL.
// Usage: node scripts/pg/convert-mysql-dump.mjs <dump.sql> [outDir]
// Writes: 001_schema.sql (tables, indexes, triggers, view, RLS),
//         002_constraints.sql (foreign keys), postgres-data.sql next to the dump (rows + sequence resets).
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';

const [,,dumpPath,outArg]=process.argv;
if(!dumpPath){console.error('Usage: node scripts/pg/convert-mysql-dump.mjs <dump.sql> [outDir]');process.exit(1);}
const outDir=resolve(outArg||'database/postgres');
const dump=readFileSync(dumpPath,'utf8');

const q=n=>'"'+n+'"';
const unbt=s=>s.replace(/`([^`]+)`/g,'"$1"');
const cols=s=>s.split(',').map(c=>q(c.trim().replace(/`/g,'')));
const shortName=(t,n)=>{let x=t+'__'+n;if(x.length>63)x=x.slice(0,54)+'_'+(hash(x)%1e8).toString(36);return x;};
function hash(s){let h=0;for(const ch of s)h=(h*31+ch.charCodeAt(0))>>>0;return h;}

const tables=[];       // {name, columns:[{name,generated,identity}], ...}
const schema=[],fks=[],triggers=[],warnings=[];

function mapType(raw,colName,table){
 let t=raw.trim(),m,check=null;
 const unsigned=/\bunsigned\b/i.test(t);t=t.replace(/\s*unsigned\b/i,'');
 if((m=/^enum\((.*)\)$/i.exec(t))){
  const vals=[...m[1].matchAll(/'((?:[^']|'')*)'/g)].map(v=>v[1]);
  const len=Math.max(...vals.map(v=>v.replace(/''/g,"'").length));
  check=`CHECK (${q(colName)} IN (${vals.map(v=>"'"+v+"'").join(',')}))`;
  return {type:`varchar(${len})`,check};
 }
 if((m=/^(var)?char\((\d+)\)$/i.exec(t)))return {type:`varchar(${m[2]})`};
 if(/^(tiny|medium|long)?text$/i.test(t))return {type:'text'};
 if(/^tinyint(\(\d+\))?$/i.test(t))return {type:'smallint'};
 if(/^smallint(\(\d+\))?$/i.test(t))return {type:unsigned?'integer':'smallint'};
 if(/^(int|integer|mediumint)(\(\d+\))?$/i.test(t))return {type:unsigned?'bigint':'integer'};
 if(/^bigint(\(\d+\))?$/i.test(t)){if(unsigned)warnings.push(`${table}.${colName}: bigint unsigned -> bigint`);return {type:'bigint'};}
 if((m=/^decimal\((\d+),(\d+)\)$/i.exec(t)))return {type:`numeric(${m[1]},${m[2]})`};
 if(/^double$/i.test(t))return {type:'double precision'};
 if(/^float$/i.test(t))return {type:'real'};
 if((m=/^(datetime|timestamp)(\((\d)\))?$/i.exec(t)))return {type:`timestamp(${m[3]||0})`};
 if(/^date$/i.test(t))return {type:'date'};
 if(/^time$/i.test(t))return {type:'time'};
 if(/^json$/i.test(t))return {type:'jsonb'};
 if(/^(tiny|medium|long)?blob$|^(var)?binary\(\d+\)$/i.test(t))return {type:'bytea'};
 throw Error(`Unhandled type "${raw}" on ${table}.${colName}`);
}
const NOW="(CURRENT_TIMESTAMP(3) AT TIME ZONE 'UTC')";
function mapDefault(d){
 if(/^NULL$/i.test(d))return 'NULL';
 if(/^CURRENT_TIMESTAMP(\(\d\))?$/i.test(d))return NOW;
 if(/^'.*'$/.test(d))return d;
 if(/^-?\d+(\.\d+)?$/.test(d))return d;
 throw Error('Unhandled default '+d);
}

// ---- CREATE TABLE blocks ----
for(const block of dump.matchAll(/CREATE TABLE `([^`]+)` \(\n([\s\S]*?)\n\) ENGINE=[^;]*;/g)){
 const table=block[1],lines=block[2].split('\n').map(l=>l.trim().replace(/,$/,''));
 const defs=[],indexes=[],info={name:table,columns:[]};
 for(const line of lines){
  let m;
  if((m=/^PRIMARY KEY \((.+)\)$/.exec(line))){defs.push(`PRIMARY KEY (${cols(m[1]).join(',')})`);continue;}
  if((m=/^UNIQUE KEY `([^`]+)` \((.+)\)$/.exec(line))){defs.push(`CONSTRAINT ${q(shortName(table,m[1]))} UNIQUE (${cols(m[2]).join(',')})`);continue;}
  if((m=/^KEY `([^`]+)` \((.+)\)$/.exec(line))){indexes.push(`CREATE INDEX ${q(shortName(table,m[1]))} ON ${q(table)} (${cols(m[2]).join(',')});`);continue;}
  if((m=/^CONSTRAINT `([^`]+)` FOREIGN KEY \((.+?)\) REFERENCES `([^`]+)` \((.+?)\)(.*)$/.exec(line))){
   fks.push(`ALTER TABLE ${q(table)} ADD CONSTRAINT ${q(shortName(table,m[1]))} FOREIGN KEY (${cols(m[2]).join(',')}) REFERENCES ${q(m[3])} (${cols(m[4]).join(',')})${m[5]};`);continue;}
  if((m=/^CONSTRAINT `([^`]+)` CHECK (.+)$/.exec(line))){defs.push(`CONSTRAINT ${q(shortName(table,m[1]))} CHECK ${unbt(m[2])}`);continue;}
  if((m=/^`([^`]+)` (.+)$/.exec(line))){
   const name=m[1];let rest=m[2].replace(/ CHARACTER SET \w+| COLLATE \w+/g,'');
   const tm=/^(enum\((?:'(?:[^']|'')*',?)+\)|\w+(?:\([\d,]+\))?(?: unsigned)?)(.*)$/i.exec(rest);
   if(!tm)throw Error('Cannot parse column '+line);
   const {type,check}=mapType(tm[1],name,table);let tail=tm[2],out=`${q(name)} ${type}`,generated=false,identity=false;
   const gen=/GENERATED ALWAYS AS \((.+)\) STORED/.exec(tail);
   if(gen){generated=true;out+=` GENERATED ALWAYS AS (${unbt(gen[1]).replace(/_utf8mb4'/g,"'")}) STORED`;tail=tail.replace(gen[0],'');}
   if(/ AUTO_INCREMENT/.test(tail)){identity=true;out+=' GENERATED BY DEFAULT AS IDENTITY';tail=tail.replace(' AUTO_INCREMENT','');}
   const onUpd=/ ON UPDATE CURRENT_TIMESTAMP(\(\d\))?/.exec(tail);if(onUpd){tail=tail.replace(onUpd[0],'');triggers.push([table,name]);}
   const dm=/ DEFAULT ('(?:[^']|'')*'|\S+)/.exec(tail);let def='';if(dm){def=' DEFAULT '+mapDefault(dm[1]);tail=tail.replace(dm[0],'');}
   if(/ NOT NULL/.test(tail))out+=' NOT NULL';tail=tail.replace(' NOT NULL','').replace(/ NULL\b/,'');out+=def;
   if(tail.trim())throw Error(`Unparsed column text "${tail}" on ${table}.${name}`);
   if(check)out+=' '+check;
   defs.push(out);info.columns.push({name,generated,identity});continue;
  }
  throw Error(`Unparsed line in ${table}: ${line}`);
 }
 schema.push(`CREATE TABLE ${q(table)} (\n  ${defs.join(',\n  ')}\n);`,...indexes,'');
 tables.push(info);
}

// ---- auto-updated timestamps (MySQL ON UPDATE CURRENT_TIMESTAMP) ----
if(triggers.length){
 schema.push(`CREATE OR REPLACE FUNCTION tejasvi_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD AND to_jsonb(NEW)->TG_ARGV[0] IS NOT DISTINCT FROM to_jsonb(OLD)->TG_ARGV[0] THEN
    NEW := jsonb_populate_record(NEW, jsonb_build_object(TG_ARGV[0], ${NOW}));
  END IF;
  RETURN NEW;
END $$;`);
 for(const [t,c] of triggers)schema.push(`CREATE TRIGGER ${q(shortName(t,c+'_touch'))} BEFORE UPDATE ON ${q(t)} FOR EACH ROW EXECUTE FUNCTION tejasvi_touch('${c}');`);
 schema.push('');
}

// ---- views ----
for(const v of dump.matchAll(/\/\*!50001 VIEW `([^`]+)` AS ([\s\S]*?) \*\/\n(\/\*!50002 WITH (\w+) CHECK OPTION \*\/)?/g)){
 const body=unbt(v[2]);
 schema.push(`CREATE VIEW ${q(v[1])} AS ${body}${v[3]?` WITH ${v[4]} CHECK OPTION`:''};`,'');
}

// ---- lock down Supabase Data API: RLS on, no policies (server connects as table owner) ----
for(const t of tables)schema.push(`ALTER TABLE ${q(t.name)} ENABLE ROW LEVEL SECURITY;`);
schema.push(`REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;`);

// ---- data ----
function parseValues(s,start){ // returns {rows, end}
 const rows=[];let i=start;
 while(true){
  while(s[i]===','||s[i]===' '||s[i]==='\n')i++;
  if(s[i]===';')return {rows,end:i};
  if(s[i]!=='(')throw Error('Expected ( at '+i);i++;
  const row=[];
  while(true){
   if(s[i]==="'"){i++;let v='';
    while(true){const ch=s[i];
     if(ch==='\\'){const n=s[i+1];v+=({'0':'\0',n:'\n',r:'\r',t:'\t',b:'\b',Z:'\x1a'})[n]??n;i+=2;}
     else if(ch==="'"){if(s[i+1]==="'"){v+="'";i+=2;}else{i++;break;}}
     else{v+=ch;i++;}}
    if(v.includes('\0'))throw Error('NUL byte in string value');
    row.push("'"+v.replace(/'/g,"''")+"'");
   }else{let j=i;while(s[j]!==','&&s[j]!==')')j++;const tok=s.slice(i,j);i=j;
    if(/^0x[0-9A-Fa-f]*$/.test(tok))row.push(`'\\x${tok.slice(2)}'::bytea`);
    else if(tok==='NULL'||/^-?[\d.eE+-]+$/.test(tok))row.push(tok);
    else throw Error('Unknown token '+tok);}
   if(s[i]===','){i++;continue;}
   if(s[i]===')'){i++;break;}
   throw Error('Bad row at '+i);
  }
  rows.push(row);
 }
}
const data=['BEGIN;',"SET LOCAL session_replication_role = replica;"];
const byName=Object.fromEntries(tables.map(t=>[t.name,t]));
let total=0;
for(const m of dump.matchAll(/INSERT INTO `([^`]+)`(?: \(([^)]*)\))? VALUES /g)){
 const t=byName[m[1]];if(!t)throw Error('Data for unknown table '+m[1]);
 // Backups omit active web sessions, so device sessions that hang off them are dead; devices sign in again.
 if(m[1]==='mobile_sessions'){warnings.push('mobile_sessions rows skipped (their parent web sessions are not in backups)');continue;}
 let names=m[2]?m[2].split(',').map(c=>c.trim().replace(/`/g,'')):t.columns.map(c=>c.name);
 const {rows}=parseValues(dump,m.index+m[0].length);
 const keep=names.map(n=>!t.columns.find(c=>c.name===n)?.generated);
 const cs=names.filter((_,k)=>keep[k]);
 for(let k=0;k<rows.length;k+=200){
  const chunk=rows.slice(k,k+200).map(r=>{if(r.length!==names.length)throw Error(`Column count mismatch in ${t.name}`);return '('+r.filter((_,x)=>keep[x]).join(',')+')';});
  const ov=t.columns.some(c=>c.identity)?' OVERRIDING SYSTEM VALUE':'';
  data.push(`INSERT INTO ${q(t.name)} (${cs.map(q).join(',')})${ov} VALUES\n${chunk.join(',\n')};`);
 }
 total+=rows.length;
}
for(const t of tables)for(const c of t.columns.filter(c=>c.identity))
 data.push(`SELECT setval(pg_get_serial_sequence('${q(t.name)}','${c.name}'), COALESCE((SELECT MAX(${q(c.name)}) FROM ${q(t.name)}),0)+1, false);`);
data.push('COMMIT;');

mkdirSync(outDir,{recursive:true});
const head='-- Generated by scripts/pg/convert-mysql-dump.mjs from a MySQL dump. Review before editing.\n';
writeFileSync(resolve(outDir,'001_schema.sql'),head+schema.join('\n')+'\n');
writeFileSync(resolve(outDir,'002_constraints.sql'),head+fks.join('\n')+'\n');
writeFileSync(resolve(dirname(resolve(dumpPath)),'postgres-data.sql'),head+data.join('\n')+'\n');
console.log(`Tables: ${tables.length}, foreign keys: ${fks.length}, auto-update timestamps: ${triggers.length}, rows: ${total}`);
for(const w of warnings)console.log('Note:',w);
